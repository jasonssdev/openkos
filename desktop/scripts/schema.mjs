// Generate, or check, the client's types from the local API's OpenAPI snapshot.
//
//   node scripts/schema.mjs          write client/schema.d.ts
//   node scripts/schema.mjs --check  fail when client/schema.d.ts differs
//
// The snapshot (tests/unit/localapi/openapi.json) is the single source of
// truth: the Python suite holds it equal to the document the engine serves, and
// this check holds the committed types equal to the snapshot. Both modes run
// the same generation, so they cannot disagree.
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const SNAPSHOT = new URL("../../tests/unit/localapi/openapi.json", import.meta.url);
const TARGET = new URL("../client/schema.d.ts", import.meta.url);
const HEADER =
  "// GENERATED by `pnpm --dir desktop generate` from tests/unit/localapi/openapi.json.\n" +
  "// Do not edit: regenerate it whenever the snapshot changes.\n\n";

export async function generate() {
  const document = JSON.parse(await readFile(SNAPSHOT, "utf8"));
  return HEADER + astToString(await openapiTS(document, { defaultNonNullable: false }));
}

async function readCommitted() {
  try {
    return await readFile(TARGET, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

const expected = await generate();
if (process.argv.includes("--check")) {
  const committed = await readCommitted();
  if (committed !== expected) {
    const why = committed === null ? "is missing" : "differs from the OpenAPI snapshot";
    console.error(`desktop/client/schema.d.ts ${why}; run \`pnpm --dir desktop generate\`.`);
    process.exit(1);
  }
  console.log("desktop/client/schema.d.ts matches the OpenAPI snapshot.");
} else {
  await writeFile(TARGET, expected);
  console.log("wrote desktop/client/schema.d.ts");
}
